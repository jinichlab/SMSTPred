# Function to write sequences to a FASTA file
def write_fasta(df, filename):
    with open(filename, "w") as f:
        for i, row in df.iterrows():
            f.write(f">{row['Entry']}\n{row['Sequence']}\n")

# Function to determine the correct n based on the threshold
def get_n_for_threshold(threshold):
    if 0.7 <= threshold <= 1.5:
        return 5
    elif 0.6 <= threshold < 0.7:
        return 4
    elif 0.5 <= threshold < 0.6:
        return 3
    elif 0.4 <= threshold < 0.5:
        return 2
    else:
        raise ValueError("Threshold out of range for this function")

def run_cd_hit_with_progress(input_file, output_file, threshold, check_interval=1):
    n = get_n_for_threshold(threshold)  # Get the correct n for the threshold
    cmd = f"cd-hit -i {input_file} -o {output_file} -c {threshold} -n {n} -T 2 -M 5000"
    print(f"Starting CD-HIT with command: {cmd}")

    # Start CD-HIT process asynchronously
    process = subprocess.Popen(cmd, shell=True, stdout=subprocess.PIPE, stderr=subprocess.PIPE)

    clstr_file = f"{output_file}.clstr"
    progress_bar = tqdm(total=100, desc="CD-HIT Clustering Progress", leave=False)

    try:
        while process.poll() is None:
            if os.path.exists(clstr_file):
                file_size = os.path.getsize(clstr_file)
                progress_bar.n = min(file_size / (10**6), 100)
                progress_bar.refresh()

            time.sleep(check_interval)

        stdout, stderr = process.communicate()
        print("CD-HIT Finished.")
        print("CD-HIT stdout:", stdout.decode())
        print("CD-HIT stderr:", stderr.decode())

    except Exception as e:
        print("An error occurred during CD-HIT execution.")
        raise e

    finally:
        progress_bar.close()

# Function to parse CD-HIT .clstr file
def parse_cd_hit_clstr(file):
    clusters = {}
    cluster_id = None
    with open(file, "r") as f:
        for line in f:
            if line.startswith(">"):
                cluster_id = line.strip()
                clusters[cluster_id] = []
            else:
                sequence_id = line.split(">")[1].split("...")[0]
                clusters[cluster_id].append(sequence_id)
    return clusters

# Function to split clusters into train and test sets
def split_clusters(clusters, train_ratio=0.8):
    cluster_ids = list(clusters.keys())
    random.shuffle(cluster_ids)
    train_size = int(train_ratio * len(cluster_ids))
    train_clusters = {k: clusters[k] for k in cluster_ids[:train_size]}
    test_clusters = {k: clusters[k] for k in cluster_ids[train_size:]}
    return train_clusters, test_clusters

# Initialize dictionaries for metrics for each label (SM, Polymer, Protein, RNA, DNA)
labels = ['SM', 'Polymer', 'Protein', 'RNA', 'DNA']
thresholds = np.arange(0.40, 1.05, 0.05)
num_runs = 5  # Number of iterations per threshold

# Initialize data storage for accuracy, AUROC, and MCC
metrics = {label: {'accuracy': [], 'auroc': [], 'mcc': []} for label in labels}

# Outer loop: Iterate over thresholds
for threshold in tqdm(thresholds, desc="Processing thresholds"):
    # Temporary storage for multiple runs at the same threshold
    temp_metrics = {label: {'accuracy': [], 'auroc': [], 'mcc': []} for label in labels}

    for run in range(num_runs):  # Inner loop: Iterate multiple times for each threshold
        print(f"Threshold: {threshold}, Run: {run + 1}")
        train_selected_rows = []
        test_selected_rows = []

        # Step 1: Write subset_df sequences to a FASTA file
        fasta_file = f"SAM_sequences_all.fasta"
        output_file = f"SAM_clustered_sequences_all"
        write_fasta(df, fasta_file)

        # Step 2: Run CD-HIT
        run_cd_hit_with_progress(fasta_file, output_file, threshold=threshold)

        # Step 3: Verify the existence of the CD-HIT output files
        clstr_file = f"{output_file}.clstr"
        if not os.path.exists(clstr_file):
            raise FileNotFoundError(f"{clstr_file} not found. Ensure CD-HIT ran successfully and the file was generated.")

        # Step 4: Parse CD-HIT output
        clusters = parse_cd_hit_clstr(clstr_file)

        # Step 5: Split clusters into train and test sets
        train_clusters, test_clusters = split_clusters(clusters)

        # Step 6: Collect sequence entries from train and test clusters
        train_sequences = [seq for cluster in train_clusters.values() for seq in cluster]
        test_sequences = [seq for cluster in test_clusters.values() for seq in cluster]

        # Step 7: Append the selected sequences' entries to train and test lists
        train_selected_rows.extend(df[df['Entry'].isin(train_sequences)].index.tolist())
        test_selected_rows.extend(df[df['Entry'].isin(test_sequences)].index.tolist())

        # Step 8: Create the final dataframes with the selected sequences from all subsets
        df_train = df.loc[train_selected_rows].reset_index(drop=True)
        df_test = df.loc[test_selected_rows].reset_index(drop=True)

        # Prepare the training and test sets
        X_train = np.vstack(df_train['Embeddings'].values)
        y_train = df_train[labels].values  # Multi-label targets
        X_test = np.vstack(df_test['Embeddings'].values)
        y_test = df_test[labels].values  # Multi-label targets

        # Create and train a multi-label classifier
        xgb_model = XGBClassifier(use_label_encoder=False, eval_metric='logloss')
        multi_output_model = MultiOutputClassifier(xgb_model)

        # Train the classifier
        multi_output_model.fit(X_train, y_train)

        # Predict on the test set
        y_pred = multi_output_model.predict(X_test)
        y_pred_proba = multi_output_model.predict_proba(X_test)

        # Collect metrics for each label
        for i, label in enumerate(labels):
            y_test_binary = y_test[:, i]
            y_pred_binary = y_pred[:, i]
            y_pred_proba_binary = y_pred_proba[i][:, 1]  # Probability of positive class

            # Compute metrics
            accuracy = accuracy_score(y_test_binary, y_pred_binary)
            auroc = roc_auc_score(y_test_binary, y_pred_proba_binary) if len(np.unique(y_test_binary)) > 1 else np.nan
            mcc = matthews_corrcoef(y_test_binary, y_pred_binary) if len(np.unique(y_test_binary)) > 1 else np.nan

            # Store metrics for this run
            temp_metrics[label]['accuracy'].append(accuracy)
            temp_metrics[label]['auroc'].append(auroc)
            temp_metrics[label]['mcc'].append(mcc)

    # Compute averages and standard deviations for each label
    for label in labels:
        metrics[label]['accuracy'].append({
            'mean': np.mean(temp_metrics[label]['accuracy']),
            'std': np.std(temp_metrics[label]['accuracy'])
        })
        metrics[label]['auroc'].append({
            'mean': np.nanmean(temp_metrics[label]['auroc']),
            'std': np.nanstd(temp_metrics[label]['auroc'])
        })
        metrics[label]['mcc'].append({
            'mean': np.nanmean(temp_metrics[label]['mcc']),
            'std': np.nanstd(temp_metrics[label]['mcc'])
        })

